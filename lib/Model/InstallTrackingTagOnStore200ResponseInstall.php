     * @param string|null $homepage_check WordPress only: whether the pixel appeared in the homepage HTML. `not_found` can be a stale page cache.
     *
     * @return self
     */
    public function setHomepageCheck($homepage_check)
    {
        if (is_null($homepage_check)) {
            throw new \InvalidArgumentException('non-nullable homepage_check cannot be null');
        }
        $allowedValues = $this->getHomepageCheckAllowableValues();
        if (!in_array($homepage_check, $allowedValues, true)) {
            throw new \InvalidArgumentException(
                sprintf(
                    "Invalid value '%s' for 'homepage_check', must be one of '%s'",
                    $homepage_check,
                    implode("', '", $allowedValues)
                )
            );
        }
        $this->container['homepage_check'] = $homepage_check;

        return $this;
    }
