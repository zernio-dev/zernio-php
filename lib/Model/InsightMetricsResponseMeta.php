    /**
     * Sets provisional_since
     *
     * @param string|null $provisional_since First day the platform may still revise or have missing. Post insights only; null on account insights and when every day is final.
     *
     * @return self
     */
    public function setProvisionalSince($provisional_since)
    {
        if (is_null($provisional_since)) {
            array_push($this->openAPINullablesSetToNull, 'provisional_since');
        } else {
            $nullablesSetToNull = $this->getOpenAPINullablesSetToNull();
            $index = array_search('provisional_since', $nullablesSetToNull);
            if ($index !== FALSE) {
                unset($nullablesSetToNull[$index]);
                $this->setOpenAPINullablesSetToNull($nullablesSetToNull);
            }
        }
        $this->container['provisional_since'] = $provisional_since;

        return $this;
    }

