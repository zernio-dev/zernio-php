     * Gets refresh_state
     *
     * @return string|null
     */
    public function getRefreshState()
    {
        return $this->container['refresh_state'];
    }

    /**
     * Sets refresh_state
     *
     * @param string|null $refresh_state Whether this request could refresh the due (stale or pending) Smart+ ads of the page.  - `refused`: TikTok refused a review call of this request over quota (40002 `OVER_QPS_LIMIT` or 40100) and Zernio paused. Carries `retryAfterSeconds`. - `paused`: no call was sent for the due ads, because a pause from an earlier refusal is still running or another request is refreshing the same advertiser (then `retryAfterSeconds` is 20). Carries `retryAfterSeconds`. - `error`: TikTok refused the batch for another reason (both halves the same way). The page is served from stored reviews and `reviewError` holds TikTok's error. `retryAfterSeconds` is null because retrying soon repeats the refusal. - `ok`: nothing blocks a retry. Every due ad was read, none was due, or the split cap or the 20-second request budget left some for the next read, which can come right away.
     *
     * @return self
     */
    public function setRefreshState($refresh_state)
    {
        if (is_null($refresh_state)) {
            throw new \InvalidArgumentException('non-nullable refresh_state cannot be null');
        }
        $allowedValues = $this->getRefreshStateAllowableValues();
        if (!in_array($refresh_state, $allowedValues, true)) {
            throw new \InvalidArgumentException(
                sprintf(
                    "Invalid value '%s' for 'refresh_state', must be one of '%s'",
                    $refresh_state,
                    implode("', '", $allowedValues)
                )
            );
        }
        $this->container['refresh_state'] = $refresh_state;

        return $this;
    }
