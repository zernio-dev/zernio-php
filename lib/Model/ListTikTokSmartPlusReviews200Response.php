    /**
     * Sets retry_after_seconds
     *
     * @param int|null $retry_after_seconds Seconds until Zernio calls TikTok's review endpoint for this advertiser and connection again (the stored pause with its jitter). Set exactly when `refreshState` is `paused` or `refused`, including stale items with nothing pending. Always equals the `Retry-After` header, which is sent exactly when this is not null.  Client rule:  - Present: wait that long before reading the page again. - null with stale or pending ads: a retry is not blocked. Read again now or on your `maxAgeSeconds` schedule; with `refreshState: error`, check `reviewError` first.
     *
     * @return self
     */
    public function setRetryAfterSeconds($retry_after_seconds)
    {
        if (is_null($retry_after_seconds)) {
            array_push($this->openAPINullablesSetToNull, 'retry_after_seconds');
        } else {
            $nullablesSetToNull = $this->getOpenAPINullablesSetToNull();
            $index = array_search('retry_after_seconds', $nullablesSetToNull);
            if ($index !== FALSE) {
                unset($nullablesSetToNull[$index]);
                $this->setOpenAPINullablesSetToNull($nullablesSetToNull);
            }
        }
        $this->container['retry_after_seconds'] = $retry_after_seconds;

        return $this;
    }

